"""Normal (licit) behaviour, simulated per customer, one shard at a time.

Each transaction is generated by exactly one customer's stream: the customer
whose behaviour drives it (the payer for outgoing payments, the payee for
money arriving from outside the bank). A payment between two of our own
customers is generated by the payer only, so shards never need to talk.

Hard negatives (legitimate activity that looks suspicious) are part of normal
behaviour on purpose: payroll fan-out, merchant card-settlement fan-in,
cash-intensive businesses depositing just under and over $10k, treasury sweeps
and intercompany transfers forming cycles, seasonal bursts, remittances.

Rates are "per month" (30.44 days) unless stated. Every parameter is marked
with its source or "assumption".
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from . import ids
